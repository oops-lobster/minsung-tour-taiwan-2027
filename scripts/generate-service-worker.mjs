async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const fullPath = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await walk(fullPath))
    else if (entry.name !== 'sw.js') files.push(fullPath)
  }
  return files
}

const files = await walk(distDir)
const records = await Promise.all(files.map(async (file) => {
  const data = await readFile(file)
  const info = await stat(file)
  return {
    path: `./${relative(distDir, file).split(sep).join('/')}`,
    data,
    size: info.size,
  }
}))

const hash = createHash('sha256')
for (const record of records) {
  hash.update(record.path)
  hash.update(record.data)
}

const version = hash.digest('hex').slice(0, 10)
const fullAssets = ['./', ...records.map((record) => record.path)]
const indexHtml = await readFile(join(distDir, 'index.html'), 'utf8')
const entryAssets = [...indexHtml.matchAll(/(?:src|href)="(\.\/[^"#?]+)"/g)].map((match) => match[1])
const guideEntryAssets = records.map((record) => record.path).filter((path) => /\/YehliuGuideView-[^/]+\.js$/.test(path))
const shellAssets = [...new Set(['./', './index.html', './offline.html', './manifest.webmanifest', './icon-192.png', './icon-512.png', ...entryAssets, ...guideEntryAssets])]
const totalSize = records.reduce((sum, record) => sum + record.size, 0)

const worker = `/* Generated by scripts/generate-service-worker.mjs */
const VERSION = ${JSON.stringify(version)}
const CACHE_PREFIX = 'minsung-tour-'
const SHELL_CACHE = \`\${CACHE_PREFIX}shell-\${VERSION}\`
const GUIDE_CACHE = \`\${CACHE_PREFIX}yehliu-\${VERSION}\`
const STAGING_CACHE = \`\${GUIDE_CACHE}-staging\`
const SHELL_ASSETS = ${JSON.stringify(shellAssets)}
const GUIDE_CORE_ASSETS = ${JSON.stringify(shellAssets)}
const FULL_ASSETS = ${JSON.stringify(fullAssets)}
const FULL_SIZE = ${totalSize}

const scopedUrl = (path) => new URL(path, self.registration.scope).toString()
const assetUrls = (paths) => paths.map(scopedUrl)

async function fetchWithTimeout(request, timeout = 12000) {
  const controller = new AbortController()
  const timeoutId = setTimeout(() => controller.abort(), timeout)
  try {
    return await fetch(request, { signal: controller.signal, cache: 'no-cache' })
  } finally {
    clearTimeout(timeoutId)
  }
}

async function fillCache(cacheName, paths) {
  const cache = await caches.open(cacheName)
  for (let index = 0; index < paths.length; index += 8) {
    const chunk = paths.slice(index, index + 8)
    await Promise.all(chunk.map(async (path) => {
      const url = scopedUrl(path)
      const response = await fetchWithTimeout(new Request(url), 20000)
      if (!response.ok) throw new Error(\`\${response.status} \${path}\`)
      await cache.put(url, response)
    }))
  }
  return cache
}

async function cacheGuide() {
  await caches.delete(STAGING_CACHE)
  try {
    const staging = await fillCache(STAGING_CACHE, FULL_ASSETS)
    const current = await caches.open(GUIDE_CACHE)
    const oldRequests = await current.keys()
    await Promise.all(oldRequests.map((request) => current.delete(request)))
    const stagedRequests = await staging.keys()
    for (const request of stagedRequests) {
      const response = await staging.match(request)
      if (response) await current.put(request, response)
    }
    await caches.delete(STAGING_CACHE)
    const names = await caches.keys()
    await Promise.all(names.filter((name) => name.startsWith(\`\${CACHE_PREFIX}yehliu-\`) && name !== GUIDE_CACHE).map((name) => caches.delete(name)))
    return guideStatus()
  } catch (error) {
    await caches.delete(STAGING_CACHE)
    throw error
  }
}

async function guideStatus() {
  const cache = await caches.open(GUIDE_CACHE)
  const urls = assetUrls(FULL_ASSETS)
  const coreUrls = assetUrls(GUIDE_CORE_ASSETS)
  const matches = await Promise.all(urls.map((url) => cache.match(url)))
  const coreMatches = await Promise.all(coreUrls.map((url) => cache.match(url)))
  const count = matches.filter(Boolean).length
  const coreCount = coreMatches.filter(Boolean).length
  return { ok: true, ready: count === urls.length, coreReady: coreCount === coreUrls.length, version: VERSION, count, total: urls.length, coreCount, coreTotal: coreUrls.length, size: FULL_SIZE }
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    await fillCache(SHELL_CACHE, SHELL_ASSETS)
    await self.skipWaiting()
  })())
})

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys()
    await Promise.all(names.filter((name) => name.startsWith(\`\${CACHE_PREFIX}shell-\`) && name !== SHELL_CACHE).map((name) => caches.delete(name)))
    await self.clients.claim()
  })())
})

self.addEventListener('message', (event) => {
  const reply = (payload) => event.ports[0]?.postMessage(payload)
  if (event.data?.type === 'SKIP_WAITING') {
    self.skipWaiting()
    return
  }
  if (event.data?.type === 'GET_YEHLIU_CACHE_STATUS') {
    event.waitUntil(guideStatus().then(reply).catch((error) => reply({ ok: false, error: error.message })))
    return
  }
  if (event.data?.type === 'CACHE_YEHLIU_GUIDE' || event.data?.type === 'REFRESH_YEHLIU_GUIDE') {
    event.waitUntil(cacheGuide().then(reply).catch((error) => reply({ ok: false, error: error.message })))
  }
})

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return
  const requestUrl = new URL(event.request.url)
  if (requestUrl.origin !== self.location.origin) return

  event.respondWith((async () => {
    // Documents are network-first so a new GitHub Pages deployment is visible on
    // the next online open. The saved shell remains the fallback when offline.
    if (event.request.mode === 'navigate') {
      try {
        const response = await fetchWithTimeout(event.request, 8000)
        if (response.ok) {
          const runtime = await caches.open(SHELL_CACHE)
          await runtime.put(event.request, response.clone())
        }
        return response
      } catch {
        return (await caches.match(event.request, { ignoreSearch: true }))
          ?? (await caches.match(scopedUrl('./index.html')))
          ?? (await caches.match(scopedUrl('./offline.html')))
      }
    }

    const cached = await caches.match(event.request)
    if (cached) return cached
    try {
      const response = await fetchWithTimeout(event.request, 8000)
      if (response.ok) {
        const runtime = await caches.open(SHELL_CACHE)
        await runtime.put(event.request, response.clone())
      }
      return response
    } catch {
      return Response.error()
    }
  })())
})
`

await writeFile(join(distDir, 'sw.js'), worker)
console.log(`Generated service worker ${version}: ${fullAssets.length} files, ${(totalSize / 1024 / 1024).toFixed(1)} MB`)
